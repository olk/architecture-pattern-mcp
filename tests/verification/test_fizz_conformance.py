def _jobs_signature(trace: Trace) -> Signature:
    client_sym: dict[str, str] = {}
    jid_sym: dict[str, str] = {}
    sig: list[Any] = []
    for step in trace.steps:
        role, _, name = step.action.rpartition(".")
        if name == "Idle":
            continue
        client_sym.setdefault(role, f"c{len(client_sym)}")
        store = step.dst["JobStore#0"]
        if name == "Submit":
            jid_sym.setdefault(f"j{store['next_jid'] - 1}", f"j{len(jid_sym)}")
        inflight = step.dst[role].get("inflight")
        statuses = tuple(
            sorted((jid_sym[jid], status) for jid, status in store["status"].items())
        )
        sig.append((client_sym[role], name, jid_sym.get(inflight), statuses))
    return tuple(sig)


class _JobsReplay:
    """Element→code map (verify/fizz/jobs_protocol.fizz header):
    Submit ↔ create_job; StartRun ↔ set_running; Cancel ↔ set_cancelled;
    Complete ↔ set_completed; Fail ↔ set_failed; JobStore ↔ JobsStore.
    """

    def __init__(self, store: JobsStore) -> None:
        self._store = store
        self._jids: dict[str, str] = {}
        self._terminal: dict[str, tuple[str, str | None]] = {}
        self._acks: set[str] = set()

    async def replay(self, trace: Trace) -> None:
        for step in trace.steps:
            await self._apply(step)
            await self._check(step)

    async def _apply(self, step: Step) -> None:
        role, _, name = step.action.rpartition(".")
        if name == "Idle":
            return
        store = step.dst["JobStore#0"]
        if name == "Submit":
            model_jid = f"j{store['next_jid'] - 1}"
            self._jids[model_jid] = await self._store.create_job(
                requirements="req", domain="dom"
            )
            return
        model_jid = step.src[role]["inflight"]
        if model_jid is None:
            raise AssertionError(f"{step.action}: no inflight in src state — unmapped action?")
        real_jid = self._jids[model_jid]
        src_status = step.src["JobStore#0"]["status"][model_jid]
        expected_success = src_status in JOBS_GUARDS[name]
        try:
            await self._transition(name, real_jid)
            success = True
        except JobStateError:
            success = False
        if success != expected_success:
            raise ConformanceViolation(
                f"{step.action} [{step.src['JobStore#0']['status']}]: {role}.{name} "
                f"from {src_status}: model says "
                f"{'accept' if expected_success else 'reject'}, real store "
                f"{'accepted' if success else 'rejected'} (J-2 guard divergence)"
            )

    async def _transition(self, name: str, real_jid: str) -> None:
        if name == "StartRun":
            await self._store.set_running(real_jid)
        elif name == "Cancel":
            await self._store.set_cancelled(real_jid)
        elif name == "Complete":
            await self._store.set_completed(real_jid, '{"result": "ok"}')
        elif name == "Fail":
            await self._store.set_failed(real_jid, "boom")
        else:
            raise AssertionError(f"unmapped jobs action: {name}")

    async def _check(self, step: Step) -> None:
        store = step.dst["JobStore#0"]
        for model_jid, model_status in store["status"].items():
            row = await self._store.get_job(self._jids[model_jid])
            if row is None:
                raise ConformanceViolation(
                    f"{step.action}: job {model_jid} missing from store (J-4)"
                )
            if row["status"] != model_status.lower():
                raise ConformanceViolation(
                    f"{step.action}: job {model_jid} status divergence — "
                    f"model {model_status}, real {row['status']}"
                )
            if model_status in MODEL_TERMINAL:
                seen = self._terminal.setdefault(model_jid, (model_status, row["result"]))
                if seen[0] != model_status or seen[1] != row["result"]:
                    raise ConformanceViolation(
                        f"{step.action}: terminal job {model_jid} left "
                        f"{seen[0]}/{seen[1]!r} for {model_status}/{row['result']!r} (J-1)"
                    )
            if str(row["created_at"]) > str(row["updated_at"]):
                raise ConformanceViolation(
                    f"{step.action}: job {model_jid} timestamps inverted — "
                    f"created {row['created_at']} > updated {row['updated_at']} (J-3)"
                )
        for role, fields in step.dst.items():
            if not role.startswith("JobClient"):
                continue
            for model_jid in fields.get("ack_cancelled", []):
                self._acks.add(model_jid)
                if not await self._store.is_cancelled(self._jids[model_jid]):
                    raise ConformanceViolation(
                        f"{step.action}: {role} acked cancel of {model_jid} "
                        f"but the store is not CANCELLED (FC-2)"
                    )


