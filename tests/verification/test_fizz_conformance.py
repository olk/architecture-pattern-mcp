def _node(slug: str, score: float) -> NodeWithScore:
    return NodeWithScore(node=TextNode(text=slug, metadata={"slug": slug}), score=score)


def _fused(fused_class: str) -> list[NodeWithScore]:
    if fused_class == "EMPTY":
        return []
    if fused_class == "ONE":
        return [_node("microservices", 0.7)]
    return [
        _node("microservices", 0.7),
        _node("legacy-monolith", 0.6),
        _node("kafka", 0.5),
    ]


def _retriever(
    fused: list[NodeWithScore],
    filter_result: list[dict[str, Any]],
    *,
    floor: float = 0.0,
    reranker_config: bool = True,
) -> HybridPatternRetriever:
    loader = MagicMock()
    loader.filter_by_domain.return_value = filter_result
    loader.get_by_name.return_value = FALLBACK_PATTERN
    dense: MagicMock = MagicMock()
    dense.retrieve.return_value = fused
    bm25: MagicMock = MagicMock()
    bm25.retrieve.return_value = []
    config = (
        MagicMock(base_url="http://tei-sidecar:80", timeout=2.0, max_batch_size=48)
        if reranker_config
        else None
    )
    return HybridPatternRetriever(
        dense_retriever=cast(Any, dense),
        bm25_retriever=cast(Any, bm25),
        pattern_loader=cast(Any, loader),
        min_fusion_score=floor,
        reranker_config=config,
    )


def _tei_transport(verdict: str) -> httpx.MockTransport:
    def handler(request: httpx.Request) -> httpx.Response:
        assert request.url.path == "/rerank", f"unexpected TEI path {request.url.path}"
        if verdict == "HTTP_ERROR":
            return httpx.Response(500, text="tei sidecar boom")
        if verdict == "SHAPE_ERROR":
            return httpx.Response(200, json={"detail": "not a list"})
        count = len(json.loads(request.content)["texts"])
        return httpx.Response(
            200,
            json=[
                {"index": count - 1 - i, "score": float(count - i)}
                for i in range(count)
            ],
        )

    return httpx.MockTransport(handler)


def _tei_signature(trace: Trace) -> Signature | None:
    dst = trace.steps[-1].dst
    reranker = dst.get("Reranker#0")
    retriever = dst.get("Retriever#0")
    if reranker is None or retriever is None or retriever["outcome"] == "NONE":
        return None
    return (reranker["verdict"], retriever["fused"], retriever["outcome"])


def _replay_tei(signature: tuple[str, str, str], trace_id: str) -> None:
    verdict, fused_class, model_outcome = signature
    where = f"{trace_id} [{verdict}/{fused_class}]"
    retriever = _retriever(_fused(fused_class), [] if fused_class == "EMPTY" else [REAL_PATTERN])
    raised: RuntimeError | None = None
    outcome: Any = None
    with patch(
        "httpx.Client", return_value=httpx.Client(transport=_tei_transport(verdict))
    ):
        try:
            outcome = retriever.retrieve(
                user_domain="microservices", normalized_domain="microservices"
            )
        except RuntimeError as exc:
            raised = exc
    if model_outcome == "FAILED":
        if raised is None:
            raise ConformanceViolation(
                f"{where}: model says FAILED (rerank error) but real retrieve() "
                f"returned a partial result with {len(outcome.patterns)} pattern(s) (RET-1)"
            )
        expected = "HTTP 500" if verdict == "HTTP_ERROR" else "non-list"
        if expected not in str(raised):
            raise ConformanceViolation(
                f"{where}: rerank error must surface the sidecar cause "
                f"({expected!r} missing): {raised!r} (TEI-1)"
            )
        return
    if raised is not None:
        raise ConformanceViolation(
            f"{where}: real retrieve() raised {raised!r} but model outcome is {model_outcome}"
        )
    if model_outcome == "FALLBACK":
        if len(outcome.patterns) != 1 or not outcome.patterns[0][0].get("is_fallback"):
            raise ConformanceViolation(
                f"{where}: model says FALLBACK but real outcome is not a tagged "
                f"fallback: {outcome.patterns!r} (FUS-3)"
            )
        return
    if not outcome.patterns or any(
        pattern.get("is_fallback") for pattern, _ in outcome.patterns
    ):
        raise ConformanceViolation(
            f"{where}: model says REAL but real outcome is empty or "
            f"fallback-tagged: {outcome.patterns!r} (FUS-1)"
        )
    if fused_class == "MANY" and any(
        "rerank_logit" not in pattern for pattern, _ in outcome.patterns
    ):
        raise ConformanceViolation(
            f"{where}: REAL after rerank must carry rerank_logit on every "
            f"pattern (rerank block did not run) (TEI-1)"
        )


def _fusion_signature(trace: Trace) -> Signature | None:
    dst = trace.steps[-1].dst.get("Retriever#0")
    if dst is None or dst["outcome"] == "NONE":
        return None
    return (
        dst["outcome"],
        dst["resolved"] > 0,
        bool(dst["floor_passed"]),
        bool(dst["tagged"]),
    )


def _replay_fusion(
    signature: tuple[str, bool, bool, bool], trace_id: str
) -> None:
    model_outcome, resolved_any, floor_passed, _tagged = signature
    where = f"{trace_id} [{model_outcome}/{resolved_any}/{floor_passed}]"
    floor = 0.05
    if resolved_any and floor_passed:
        fused, filter_result = [_node("microservices", 0.7)], [REAL_PATTERN]
    elif resolved_any:
        fused, filter_result = [_node("microservices", 0.0)], [REAL_PATTERN]
    else:
        fused, filter_result = [], []
    retriever = _retriever(fused, filter_result, floor=floor, reranker_config=False)
    result = retriever.retrieve(
        user_domain="microservices", normalized_domain="microservices"
    )
    if model_outcome == "REAL":
        if not result.patterns:
            raise ConformanceViolation(f"{where}: REAL must resolve >= 1 pattern (FUS-1)")
        best = result.patterns[0][1]
        if best < floor:
            raise ConformanceViolation(
                f"{where}: REAL score {best} below floor {floor} (FUS-2)"
            )
        if any(p.get("is_fallback") for p, _ in result.patterns):
            raise ConformanceViolation(
                f"{where}: REAL outcome carries the fallback tag (FUS-3)"
            )
    elif len(result.patterns) != 1 or not result.patterns[0][0].get("is_fallback"):
        raise ConformanceViolation(
            f"{where}: fallback must carry the is_fallback sentinel (FUS-3)"
        )


