class ConformanceViolation(AssertionError):
    """A replayed model trace diverged from the real implementation."""


@dataclass(frozen=True)
class Step:
    action: str
    src: dict[str, Any]
    dst: dict[str, Any]


@dataclass(frozen=True)
class Trace:
    trace_id: str
    steps: tuple[Step, ...]


def _load_graph(spec: str) -> Graph:
    path = CORPUS_DIR / f"{spec}.json"
    if not path.exists():
        raise FileNotFoundError(
            f"conformance corpus missing: {path} — run `make regen-fizz-traces`"
        )
    raw = json.loads(path.read_text(encoding="utf-8"))
    if raw.get("schema") != 1:
        raise ValueError(f"unsupported corpus schema in {path}: {raw.get('schema')}")
    graph = Graph(nodes=raw["nodes"], adj={i: [] for i in range(len(raw["nodes"]))})
    for edge in raw["edges"]:
        graph.adj[edge["from"]].append(Edge(name=edge["action"], dest=edge["to"]))
    for src in graph.adj:
        graph.adj[src].sort(key=lambda e: (e.name, e.dest))
    return graph


def _load_traces(spec: str) -> list[Trace]:
    graph = _load_graph(spec)
    walks, uncovered = cover_edges(graph, COVER_BUDGET_TRACES, COVER_BUDGET_LEN)
    if uncovered:
        pytest.fail(
            f"corpus {spec} cannot be edge-covered within budget "
            f"({len(uncovered)} edges left) — raise COVER_BUDGET_TRACES"
        )
    return [
        Trace(
            trace_id=f"{spec}#T{i + 1:03d}",
            steps=tuple(
                Step(action=name, src=graph.nodes[src], dst=graph.nodes[dest])
                for src, name, dest in walk
            ),
        )
        for i, walk in enumerate(walks)
    ]


Signature = tuple[Any, ...]


def _signature_replays(spec: str, signature: Callable[[Trace], Any]) -> list[tuple[Signature, Trace]]:
    seen: dict[Signature, Trace] = {}
    for trace in _load_traces(spec):
        sig = signature(trace)
        if sig is not None:
            seen.setdefault(sig, trace)
    return [(sig, trace) for sig, trace in sorted(seen.items(), key=lambda kv: repr(kv[0]))]


