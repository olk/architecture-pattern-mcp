def test_vacuity_error_swallowing_reranker_fires_tei1() -> None:
    error_sigs = [sig for sig, _ in _TEI_REPLAYS if sig[0] == "HTTP_ERROR" and sig[1] == "MANY"]
    assert error_sigs, "corpus lost the HTTP_ERROR/MANY signature — vacuity oracle is vacuous"
    with patch(
        "src.patterns.retriever.SafeTEIReranker",
        return_value=_ErrorSwallowingReranker(base_url="http://tei-sidecar:80"),
    ):
        with pytest.raises(ConformanceViolation):
            _replay_tei(error_sigs[0], "vacuity/FG-23")
