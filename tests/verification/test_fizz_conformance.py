"""
L4 conformance replay — FizzBee state graphs against the real implementation.

The corpora under ``fizz_corpus/`` are canonical FizzBee state graphs
(exhaustive runs, regenerated by ``make regen-fizz-traces`` when a spec
changes). This module re-derives rooted edge-covering walks from each graph
and replays them against the REAL code — the Python-native stand-in for
FizzBee MBT adapters, which upstream ships only for Go/Java/Rust/TypeScript
(fizzbee plan §5.1 extension; ledger: verify/fizz/README.md).

Refinement mappings and their assertion semantics:

- ``jobs_protocol.fizz`` — step-by-step replay: every model action maps to
  one real ``JobsStore`` call; the model's guard outcome (dst state) must
  match the real accept/``JobStateError`` outcome, and the abstract state
  (job status) must match the store after every step. Properties checked
  per step: J-1 (terminal immutability), J-2 (guard agreement), J-3
  (created_at <= updated_at), J-4 (one row per job), FC-2 (ack honesty).
  Traces are deduped to distinct execution signatures under client
  symmetry and job-id renaming — the model's jobs are independent, so
  interleavings that rename to the same execution are one real run.
- ``tei_fallback.fizz`` — outcome-equivalence replay: the real code runs
  the whole protocol inside one synchronous ``retrieve()`` call, so a trace
  replays as ONE real retrieval with the transport/loader injected from the
  trace's final model state. Asserted: TEI-1 (a body exists only for the
  OK verdict — errors raise, never partial results) and RET-1 (a rerank
  error propagates, outcome FAILED).
- ``retrieval_fusion.fizz`` — outcome-equivalence replay over the
  resolution tail: FUS-1 (REAL implies >= 1 pattern), FUS-2 (REAL implies
  the floor passed), FUS-3 (every fallback carries ``is_fallback``).

Vacuity (repo rule: every oracle must be able to fail): the
``TestConformanceVacuity``-style tests plant one mutant per check family
and assert the harness fires — a cancel write that never lands (FG-15
class), a stale-timestamp writer (J-3 clock-skew class), and an error
swallowing reranker (FG-23 class).

Corpus integrity: ``test_corpus_edge_coverage`` asserts each checked-in
graph still edge-covers 100% of its non-stutter transitions (a stale
corpus — spec changed without regen — fails here, not silently).
"""

